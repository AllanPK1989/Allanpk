log = logging.getLogger(__name__)
KINDS = ("morning", "evening", "weekly")
DISCLAIMER = "Personal analysis generated by your investment app. Not advice from a SEBI-registered investment adviser."


def _since(db: Session, kind: str) -> datetime:
    now = datetime.now(timezone.utc)
    if kind == "weekly":
        return now - timedelta(days=7)
    last = db.scalar(select(Digest).where(Digest.kind.in_(["morning", "evening"])).order_by(Digest.created_at.desc()))
    floor = now - timedelta(hours=36)
    if last and last.created_at:
        created = last.created_at if last.created_at.tzinfo else last.created_at.replace(tzinfo=timezone.utc)
        return max(floor, created - timedelta(hours=1))
    return now - timedelta(hours=24)


def gather(db: Session, kind: str, market: MarketData) -> dict[str, Any]:
    insts = services.followed_instruments(db)
    since = _since(db, kind)
    with ThreadPoolExecutor(max_workers=3) as ex:
        f_macro = ex.submit(market.macro_snapshot)
        f_quotes = ex.submit(market.quotes, [i.symbol for i in insts]) if insts else None
        macro = f_macro.result()
        quotes = f_quotes.result() if f_quotes else {}
    snap = services.portfolio_snapshot(db, market=market)
    held = {h["symbol"] for h in snap["holdings"] if h["open"]}

    week: dict[str, float | None] = {}
    if kind == "weekly" and insts:
        with ThreadPoolExecutor(max_workers=6) as ex:
            week = dict(zip([i.symbol for i in insts], ex.map(lambda i: services.recent_change(market, i.symbol, 7), insts)))

    movers = []
    for i in insts:
        q = quotes.get(i.symbol)
        movers.append({"symbol": i.symbol, "name": i.name, "class": i.asset_class, "held": i.symbol in held,
                       "pinned": i.pinned, "price": q.price if q else None, "currency": q.currency if q else i.currency,
                       "day_pct": q.change_pct if q else None, "week_pct": week.get(i.symbol)})
    key = "week_pct" if kind == "weekly" else "day_pct"
    movers.sort(key=lambda m: -abs(m[key] or 0))

    news_by_inst: dict[str, list[dict[str, Any]]] = {}
    for i in insts:
        items = news_query.recent(db, instrument_ids=[i.id], since=since, limit=20)
        items.sort(key=lambda n: (news_query.IMPACT_RANK.get(n.impact, 3), -n.published_at.timestamp()))
        if items:
            news_by_inst[i.symbol] = [_news(n) for n in items[: (4 if i.symbol in held or i.pinned else 2)]]
    market_news = news_query.recent(db, since=since, scope="market", limit=60)
    market_news.sort(key=lambda n: (news_query.IMPACT_RANK.get(n.impact, 3), -n.published_at.timestamp()))

    events = []
    stocks = [i for i in insts if i.asset_class == "stock" and (kind == "weekly" or i.symbol in held or i.pinned)][:40]
    horizon = datetime.now(timezone.utc).date() + timedelta(days=14 if kind == "weekly" else 3)
    with ThreadPoolExecutor(max_workers=6) as ex:
        for inst, f in zip(stocks, ex.map(lambda i: market.fundamentals(i.symbol), stocks)):
            for d in f.get("next_earnings") or []:
                try:
                    dd = datetime.fromisoformat(str(d)[:10]).date()
                except ValueError:
                    continue
                if datetime.now(timezone.utc).date() <= dd <= horizon:
                    events.append({"date": dd.isoformat(), "symbol": inst.symbol, "name": inst.name, "event": "Results"})
    events.sort(key=lambda e: e["date"])

    alerts = list(db.scalars(select(AlertLog).where(AlertLog.created_at >= since).order_by(AlertLog.created_at.desc()).limit(20)))
    data: dict[str, Any] = {
        "kind": kind, "generated_at": services.now_local().strftime("%a %d %b %Y %H:%M IST"), "demo": market.demo,
        "market": macro, "portfolio": {"totals": snap["totals"], "allocation": snap["allocation"],
                                       "top_holdings": [{k: h[k] for k in ("symbol", "name", "value", "pnl_pct", "day_change_pct", "weight_pct")}
                                                        for h in snap["holdings"] if h["open"]][:10]},
        "movers": movers[:40], "news_by_instrument": news_by_inst,
        "market_news": [_news(n) for n in market_news[:15]], "events": events[:20],
        "alerts": [{"title": a.title, "body": a.body} for a in alerts],
    }
    if kind == "weekly":
        try:
            data["rebalance"] = services.rebalance_plan(db, market=market)
            data["risk"] = services.portfolio_risk(db, market=market)
        except Exception as e:  # nice-to-have
            log.warning("weekly portfolio extras failed: %s", e)
    return data


def _news(n) -> dict[str, Any]:
    return {"title": n.title, "source": n.source, "url": n.url, "summary": n.summary or n.snippet,
            "sentiment": n.sentiment, "impact": n.impact, "published_at": n.published_at.isoformat()}


def _title(kind: str, data: dict[str, Any]) -> str:
    by = {r["symbol"]: r for r in data["market"]["markets"]}
    bits = []
    for sym, label in (("^NSEI", "Nifty"), ("^GSPC", "S&P"), ("CRYPTO:BTC_USDT", "BTC")):
        r = by.get(sym)
        if r and r.get("change_pct") is not None:
            bits.append(f"{label} {r['change_pct']:+.1f}%")
    day = services.now_local().strftime("%a %d %b")
    name = {"morning": "Morning digest", "evening": "Evening digest", "weekly": "Weekly review"}[kind]
    return f"{name} · {day}" + (f": {', '.join(bits)}" if bits else "")


def tables_markdown(kind: str, data: dict[str, Any], app_url: str) -> str:
    out = ["## Market snapshot", "| Market | Last | Change |", "|---|---:|---:|"]
    for r in data["market"]["markets"]:
        if r.get("price") is not None:
            out.append(f"| {r['label']} | {fmt_num(r['price'])} | {fmt_pct(r.get('change_pct'))} |")
    if data["market"].get("rates"):
        out += ["", "| Rate / macro | Value | As of |", "|---|---:|---|"]
        out += [f"| {r['label']} | {r['value']:.2f} | {r['date']} |" for r in data["market"]["rates"]]
    t = data["portfolio"]["totals"]
    if t.get("value"):
        out += ["", "## Portfolio", "| Value | Today | Total P&L | XIRR |", "|---:|---:|---:|---:|",
                f"| {fmt_inr(t['value'])} | {fmt_inr(t['day_change'])} ({fmt_pct(t.get('day_change_pct'))}) | "
                f"{fmt_inr(t['pnl'])} ({fmt_pct(t.get('pnl_pct'))}) | {fmt_pct(t.get('xirr_pct'))} |"]
    key = "week_pct" if kind == "weekly" else "day_pct"
    movers = [m for m in data["movers"] if m.get(key) is not None][:15]
    if movers:
        out += ["", "## Your followed instruments", f"| Instrument | Price | {'Week' if kind == 'weekly' else 'Today'} |",
                "|---|---:|---:|"]
        for m in movers:
            tag = " · held" if m["held"] else (" · pinned" if m["pinned"] else "")
            out.append(f"| {md_escape(m['name'])} ({md_escape(m['symbol'])}){tag} | {fmt_num(m['price'])} {m['currency'] or ''} | {fmt_pct(m[key])} |")
    if data["news_by_instrument"]:
        out += ["", "## News on what you follow"]
        names = {m["symbol"]: m["name"] for m in data["movers"]}
        for sym, items in data["news_by_instrument"].items():
            out.append(f"**{md_escape(names.get(sym, sym))}**")
            out.append("")
            for n in items:
                imp = " · **high impact**" if n["impact"] == "high" else ""
                out.append(f"- [{md_escape(n['title'])}]({n['url']}) — {md_escape(n['source'])}{imp}"
                           + (f"<br><small>{md_escape(n['summary'][:220])}</small>" if n.get("summary") else ""))
            out.append("")
    if data["market_news"]:
        out += ["## Market headlines", ""]
        out += [f"- [{md_escape(n['title'])}]({n['url']}) — {md_escape(n['source'])}" for n in data["market_news"][:10]]
    if data["events"]:
        out += ["", "## Coming up", "| Date | Event |", "|---|---|"]
        out += [f"| {e['date']} | {md_escape(e['name'])}: {e['event']} |" for e in data["events"]]
    return "\n".join(out)


def template_narrative(kind: str, data: dict[str, Any]) -> str:
    """Used when AI is off or fails: a short factual summary from the numbers."""
    lines = []
    if data.get("demo"):
        lines.append("_Demo mode: all numbers below are made up._\n")
    lines.append("## Summary")
    by = {r["symbol"]: r for r in data["market"]["markets"]}
    for sym in ("^NSEI", "^BSESN", "^GSPC", "^IXIC", "USDINR=X", "GC=F", "CL=F", "CRYPTO:BTC_USDT"):
        r = by.get(sym)
        if r and r.get("change_pct") is not None:
            lines.append(f"- {r['label']}: {fmt_num(r['price'])} ({fmt_pct(r['change_pct'])})")
    key = "week_pct" if kind == "weekly" else "day_pct"
    big = [m for m in data["movers"] if m.get(key) is not None and abs(m[key]) >= 2][:6]
    if big:
        lines.append("\n## Biggest moves in your list")
        lines += [f"- {md_escape(m['name'])}: {fmt_pct(m[key])}" for m in big]
    high = [n for items in data["news_by_instrument"].values() for n in items if n["impact"] == "high"]
    if high:
        lines.append("\n## High-impact news")
        lines += [f"- {md_escape(n['title'])} ({md_escape(n['source'])})" for n in high[:6]]
    lines.append("\n_AI commentary is off (no API key), so this digest shows data only._")
    return "\n".join(lines)


def build(db: Session, kind: str, market: MarketData) -> Digest:
    if kind not in KINDS:
        raise ValueError(f"kind must be one of {KINDS}")
    s = get_settings()
    data = gather(db, kind, market)
    narrative = None
    if llm.ai_enabled():
        system = prompts.DIGEST.format(sections=prompts.DIGEST_SECTIONS[kind], words=650 if kind == "weekly" else 450)
        ai_data = {k: v for k, v in data.items()}
        narrative = llm.write(system, "Digest data:\n" + json.dumps(ai_data, default=str, ensure_ascii=False))
    title = _title(kind, data)
    digest = Digest(kind=kind, title=title, markdown="", html="", data={}, ai_generated=bool(narrative))
    db.add(digest)
    db.flush()
    app_url = f"{s.base_url.rstrip('/')}/digests/{digest.id}"
    body = (narrative or template_narrative(kind, data)) + "\n\n" + tables_markdown(kind, data, app_url)
    body += f"\n\n---\n_{DISCLAIMER}_"
    digest.markdown = body
    digest.html = to_html(body)
    digest.data = {"movers": data["movers"][:20], "events": data["events"], "portfolio": data["portfolio"]["totals"]}
    db.flush()
    return digest


def deliver(db: Session, digest: Digest) -> dict[str, Any]:
    s = get_settings()
    settings = services.get_all_settings(db)
    app_url = f"{s.base_url.rstrip('/')}/digests/{digest.id}"
    out = {"emailed": False, "pushed": 0}
    if settings.get("email_digests", True):
        html = email_html(digest.title, digest.html, app_url=app_url, footer=DISCLAIMER)
        out["emailed"] = email.send(digest.title, html, digest.markdown)
        if out["emailed"]:
            digest.emailed_at = datetime.now(timezone.utc)
    if settings.get("push_digests", True):
        movers = [m for m in digest.data.get("movers", []) if m.get("day_pct") is not None][:3]
        body = ", ".join(f"{m['name'][:24]} {m['day_pct']:+.1f}%" for m in movers) or "Tap to read."
        out["pushed"] = push.send_all(db, title=digest.title, body=body, url=f"/digests/{digest.id}", tag=f"digest-{digest.kind}")
        if out["pushed"]:
            digest.pushed_at = datetime.now(timezone.utc)
    db.flush()
    return out


def followed_count(db: Session) -> int:
    return len(list(db.scalars(select(Instrument.id).where(Instrument.followed.is_(True)))))
